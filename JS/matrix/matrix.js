btn_start.onclick = function(){
    my_matrix = Matrix.from(example).append(Matrix.identity(4));
    iterator = my_matrix.guassian_elimination(7);
    el_done.innerHTML = "no (just started)";
    el_value.innerHTML = my_matrix.toString();
}
